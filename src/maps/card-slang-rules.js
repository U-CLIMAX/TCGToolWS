const BR_REGEX = /<br\s*\/?>/i

/**
 * 根據卡片效果文字 (effect) 與卡片屬性提取符合的俗稱標籤列表
 * @param {string|object} effectOrCard - 卡片效果文字或卡片物件
 * @param {object} [cardObj] - 卡片物件（可選，提供 level, cost, type 等）
 * @returns {string[]} 符合的俗稱的陣列
 */
export const extractCardSlangs = (effectOrCard, cardObj = null) => {
  let effect = ''
  let card = cardObj

  if (typeof effectOrCard === 'string') {
    effect = effectOrCard
  } else if (effectOrCard && typeof effectOrCard === 'object') {
    card = effectOrCard
    effect = card.effect || ''
  }

  if (!effect || typeof effect !== 'string') return []

  const abilities =
    effect.includes('<br') || effect.includes('<BR') ? effect.split(BR_REGEX) : [effect]

  const matched = []
  const defsLen = WS_SLANG_DEFINITIONS.length
  const abLen = abilities.length

  for (let i = 0; i < defsLen; i++) {
    const item = WS_SLANG_DEFINITIONS[i]
    for (let j = 0; j < abLen; j++) {
      if (item.test(abilities[j], effect, card)) {
        matched.push(item.name)
        break
      }
    }
  }

  return matched
}
